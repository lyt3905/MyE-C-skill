"""Reconcile the read-only source inventory with actual migration provenance."""
import collections,json
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
reports=ROOT/'reports'
inventory=json.loads((reports/'asset-inventory.json').read_text(encoding='utf-8'))
provenance=json.loads((reports/'migration-provenance.json').read_text(encoding='utf-8'))
targets={r['source']:r['target'] for r in provenance}
known={
    'prompts/image_action_decision.v2.md':['scripts/ai_judge/image_action_decision.py'],
    'prompts/image_quality.v2.md':['scripts/ai_judge/image_quality_v2.py'],
    'prompts/image_edit.v2.md':['scripts/v2_remediation.py'],
    'scripts/config/budget.v2.json':['scripts/workflow_runner.py'],
    'scripts/config/policy.v2.json':['scripts/audit_one.py','scripts/policy_engine.py'],
    'scripts/config/watermark.matching.v3.json':['scripts/ai_judge/watermark_contract.py'],
    'scripts/config/token.capabilities.v1.json':['scripts/token_budget.py'],
    'scripts/config/schemas/image-action-decision.v2.schema.json':['scripts/ai_judge/image_action_decision.py'],
    'references/SOP-商品标题重写.md':['scripts/title_rules.py (only parsed translation table extracted)'],
    'local/models/lama/big-lama.pt':['scripts/image_repairs_v2.py:lama_torchscript','scripts/job_manager.py (explicit model pinning only)'],
}
for row in inventory:
    name=row['path']
    if '__pycache__' in Path(name).parts or name.endswith(('.pyc','.pyo')):
        row.update(category='LEDGER_OR_CACHE',target=None,method='READ_ONLY_RETAIN',runtime_required=False,purpose='Generated bytecode; never migrated')
    elif name in targets:
        row['target']=targets[name]
        if row['target'].startswith('tests/fixtures/'):
            row.update(method='FIXED_TEST_COPY',runtime_required=False,purpose='Fixed offline regression evidence, never active Job data',
                callers=['tests: archived acceptance fixture reader'] if '/archived-inputs/' in row['target'] else ['tests/test_visual_versions.py' if 'visual_versions' in row['target'] else 'tests/test_v2_reusable_rules.py'])
    if name in known:row['callers']=known[name]
    if name.startswith('scripts/config/') and not row['callers']:
        row['callers']=['Explicit config load by existing validated workflow/adapter; regression contract consumers']
    if name=='local/models/lama/big-lama.pt':
        row.update(method='EXTERNAL_DEPENDENCY',target='models/resources.json (checksum/install contract)',runtime_required=False,
            purpose='Optional trained TorchScript weight; not distributed; explicit independent path required',risk='Distribution license not established; no automatic copy or download')
    if name=='references/SOP-商品标题重写.md':
        row.update(method='DERIVE_PROGRAM_TABLE',target='src/mye_c_automation/config/title-mappings.md',runtime_required=False,purpose='Only deterministic translation table is a program asset; original SOP retained')
(reports/'asset-inventory.json').write_text(json.dumps(inventory,ensure_ascii=False,indent=2),encoding='utf-8')
counts=collections.Counter(r['category'] for r in inventory)
(reports/'asset-inventory.md').write_text('# Asset inventory\n\nFull per-file classification, SHA256, callers, dependencies, target, method, sensitivity and validation: `asset-inventory.json`. Reconciled with actual extraction in `migration-provenance.json`.\n\n'+
    '\n'.join(f'- {name}: {count}' for name,count in sorted(counts.items()))+
    '\n\nGenerated bytecode and caches are never fixtures. Only 26 archived input/contrast files are fixed regression assets, plus the existing V2 fixture set. Optional trained weights remain external with a recorded checksum. UNKNOWN, secrets, old Jobs, authorizations and databases remain at source. Original Skill instructions and SOPs are not runtime inputs.\n\nNew software-authored resources (not source copies): CLI, paths/resources helpers, Fake adapters, installation metadata, model/image-options schemas and configuration Schema connections. The authorization Schema only adds V2 actions already allowed by the existing validator; it does not expand the policy whitelist.\n',encoding='utf-8')
print(json.dumps({'source_files':len(inventory),'categories':dict(counts)}))
